/**
 * The logo as terminal lines. `unicode: false` swaps the blocks for ASCII on terminals that
 * cannot draw them.
 */
export function brandLogo(unicode = true): string[] {
  if (unicode) return [...LOGO_ART];
  return LOGO_ART.map((line) =>
    line.replaceAll('█', '#').replaceAll('▀', '"').replaceAll('▄', '.'),
  );
}
